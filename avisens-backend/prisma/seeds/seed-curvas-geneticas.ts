export async function sembrarCurvasGeneticas(prisma: PrismaClient) {
  for (const linea of LINEAS) {
    const { id: lineaId, activo } = await prisma.lineaGenetica.upsert({
      where: { codigo: linea.codigo },
      update: {},
      create: {
        codigo: linea.codigo,
        nombre: linea.nombre,
        descripcion: linea.descripcion,
      },
      select: { id: true, activo: true },
    });
    if (!activo) continue;

    for (const [sexo, filas] of Object.entries(linea.curvas) as [
      SexoCurva,
      Fila[],
    ][]) {
      await prisma.$transaction(async (tx) => {
        const yaSembrada = await tx.curvaGeneticaVersion.findFirst({
          where: { linea_genetica_id: lineaId, sexo, fuente: linea.fuente },
          select: { id: true },
        });
        if (yaSembrada) return;

        const [ultima, vigente] = await Promise.all([
          tx.curvaGeneticaVersion.findFirst({
            where: { linea_genetica_id: lineaId, sexo },
            orderBy: { version: 'desc' },
            select: { version: true },
          }),
          tx.curvaGeneticaVersion.findFirst({
            where: { linea_genetica_id: lineaId, sexo, vigente: true },
            select: { id: true },
          }),
        ]);

        await tx.curvaGeneticaVersion.create({
          data: {
            linea_genetica_id: lineaId,
            sexo,
            version: (ultima?.version ?? 0) + 1,
            estado: 'publicada',
            vigente: !vigente,
            fuente: linea.fuente,
            fecha_publicacion: new Date(),
            puntos: {
              create: filas.map(([dia, peso, diario, acumulado, fcr]) => ({
                dia,
                peso_esperado_g: peso,
                consumo_diario_g: diario,
                consumo_acumulado_g: acumulado,
                fcr_objetivo: fcr,
              })),
            },
          },
        });
      });
    }
  }
}
